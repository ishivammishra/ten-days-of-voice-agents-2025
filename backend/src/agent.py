# ------------------------------
# USER SCENE / IMPROV STATE
# ------------------------------
@dataclass
class Userdata:
    # Scene-specific (improv) state
    scene_id: Optional[str] = None
    scene_title: Optional[str] = None
    scene_style: Optional[str] = None
    location: Optional[str] = None
    characters: List[str] = field(default_factory=list)
    beat_history: List[str] = field(default_factory=list)
    scene_active: bool = False
    turns_in_scene: int = 0
    greeted: bool = False
    created_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())

    # Improv-game state
    improv_state: Dict[str, Any] = field(default_factory=lambda: {
        "player_name": None,
        "current_round": 0,
        "max_rounds": 3,
        "rounds": [],
        "phase": "intro",  # intro | awaiting_improv | reacting | done
        "current_scenario": None,
        "round_timeout_seconds": 25,  # fallback timeout if you want timing heuristics
    })


# ------------------------------
# Pydantic models for tools
# ------------------------------
class StartSceneInput(BaseModel):
    title: Optional[str] = Field(default=None)
    style: Optional[str] = Field(default=None)
    location: Optional[str] = Field(default=None)
    characters: Optional[str] = Field(default=None)


class RecordBeatInput(BaseModel):
    beat_text: str = Field(description="Short note of what just happened in the story.")


# ------------------------------
# Simple scenarios (can be extended or generated by LLM)
# ------------------------------
SCENARIOS = [
    "You are a barista who must tell a customer that their latte is a portal to another dimension.",
    "You are a time-travelling tour guide explaining smartphones to someone from the 1800s.",
    "You are a restaurant waiter who must calmly tell a customer that their order has escaped the kitchen.",
    "You are a customer trying to return an obviously cursed object to a skeptical shop owner.",
    "You are an astronaut complaining about how the spaceship's coffee machine has opinions.",
]

def pick_scenario(used: List[str]) -> str:
    choices = [s for s in SCENARIOS if s not in used]
    if not choices:
        # if exhausted, allow repeats and randomize
        choices = SCENARIOS
    return random.choice(choices)


